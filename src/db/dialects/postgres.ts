import { sql } from 'drizzle-orm'
import {
	index,
	boolean as pgBoolean,
	integer as pgInteger,
	pgTable,
	text as pgText,
	timestamp as pgTimestamp,
	uniqueIndex,
	varchar,
} from 'drizzle-orm/pg-core'
import { drizzle } from 'drizzle-orm/postgres-js'
import { migrate } from 'drizzle-orm/postgres-js/migrator'
import postgres from 'postgres'
import { newId } from '../id'

/**
 * PostgreSQL dialect (driver: postgres.js).
 * DATABASE_URL example: postgresql://user:pass@localhost:5432/app
 *
 * Every dialect file exports the same names, so schema files and services
 * never import from `drizzle-orm/<dialect>-core` directly.
 */
export const dialect = { name: 'postgres', kit: 'postgresql', betterAuth: 'pg' } as const

export const table = pgTable
export type { PgTable as AnyTable } from 'drizzle-orm/pg-core'
export { index, uniqueIndex }

export const column = {
	/** Primary key: UUID v7 generated by the app (portable, sortable). */
	id: (name = 'id') => varchar(name, { length: 36 }).primaryKey().$defaultFn(newId),
	/** Column that stores another table's `id`. */
	foreignId: (name: string) => varchar(name, { length: 36 }),
	string: (name: string, length = 255) => varchar(name, { length }),
	text: (name: string) => pgText(name),
	boolean: (name: string) => pgBoolean(name),
	integer: (name: string) => pgInteger(name),
	timestamp: (name: string) => pgTimestamp(name, { mode: 'date', precision: 3, withTimezone: true }),
}

export function connect<TSchema extends Record<string, unknown>>(url: string, schema: TSchema) {
	const client = postgres(url, { max: 10, onnotice: () => {} })
	const db = drizzle(client, { schema })

	return {
		db,
		ping: () => db.execute(sql`select 1`),
		migrate: (migrationsFolder: string) => migrate(db, { migrationsFolder }),
		close: () => client.end(),
	}
}

/**
 * Database provisioning, used by `bun db:migrate` before connecting.
 * Connects to the `postgres` maintenance database of the same server.
 */
export const provisioning = {
	databaseName: (url: string) => decodeURIComponent(new URL(url).pathname.slice(1)),

	async exists(url: string) {
		return withMaintenance(url, async (sql) => {
			const rows = await sql`select 1 from pg_database where datname = ${provisioning.databaseName(url)}`
			return rows.length > 0
		})
	},

	async create(url: string) {
		const name = assertIdentifier(provisioning.databaseName(url))
		await withMaintenance(url, (sql) => sql.unsafe(`create database "${name}"`))
	},
}

async function withMaintenance<T>(url: string, run: (sql: postgres.Sql) => Promise<T>): Promise<T> {
	const maintenance = new URL(url)
	maintenance.pathname = '/postgres'
	const sql = postgres(maintenance.toString(), { max: 1, onnotice: () => {} })
	try {
		return await run(sql)
	} finally {
		await sql.end()
	}
}

/** Database names are interpolated into DDL, so only plain identifiers are accepted. */
function assertIdentifier(name: string) {
	if (!/^[A-Za-z0-9_][A-Za-z0-9_$-]{0,62}$/.test(name)) throw new Error(`Invalid database name "${name}"`)
	return name
}
